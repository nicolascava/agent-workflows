import { expect, test } from "bun:test";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { checkCopy } from "./check-pr-copy.ts";
const title = "Fix the login redirect";
const body = "## Summary\n\n- Return users to their requested page\n\n## Test plan\n\n- [x] Run the focused tests and confirm they pass\n- [ ] Check the browser\n\nRelated: https://github.com/example/project/issues/12\n";
const rules = (t = title, b = body, closing = false) => checkCopy(t, b, closing).violations.map(v => v.rule);
test("accepts the visible contract and optional infrastructure evidence", () => {
  expect(checkCopy(title, body).ok).toBe(true);
  expect(checkCopy(title, `${body}\n## Plan output\n\n\`\`\`text\nNo changes\n\`\`\`\n\n## Rollback\n\nRevert the change\n`).ok).toBe(true);
});
test("ports title length, prefix, issue number and trailing period checks", () => {
  for (const [t, rule] of [["Add " + "x".repeat(73), "title-length"], ["feat(ui): Add login", "title-prefix"], ["Fix login #12", "title-issue-id"], ["Fix login.", "title-trailing-period"]]) expect(rules(t)).toContain(rule);
});
test("ports section presence, ordering, duplicates and summary bullet limits", () => {
  for (const b of [body.replace("## Summary", "## Details"), body.replace("## Test plan", "## Checks"), body.replace("## Summary", "## Test plan").replace("## Test plan\n\n- [x]", "## Summary\n\n- [x]"), body + "\n## Summary\n", body.replace("- Return users to their requested page", "No bullet")]) expect(checkCopy(title, b).ok).toBe(false);
});
test("headings and checkboxes in comments or fences cannot satisfy the contract", () => {
  for (const b of [`<!--\n${body}\n-->`, `\`\`\`md\n${body}\n\`\`\``, body.replace("- [x]", "  - [x]").replace("- [ ]", "  - [ ]")]) expect(checkCopy(title, b).ok).toBe(false);
});
test("ports unclosed comments and fences and rejects hidden new contracts", () => {
  for (const b of [body + "\n<!-- hidden", body + "\n```text\nhidden", body + "\n<!-- review-scope/v1 {} -->"]) expect(checkCopy(title, b).ok).toBe(false);
});
test("accepts only an unchanged legacy review comment during an update", () => {
  const legacy = "\n<!-- review-scope/v1 {\"scope\":\"preserved\"} -->";
  const original = body + legacy;
  expect(checkCopy(title, original, false, original).ok).toBe(true);
  expect(checkCopy(title, original.replace("preserved", "altered"), false, original).ok).toBe(false);
  expect(checkCopy(title, body, false, original).ok).toBe(false);
  expect(checkCopy(title, body + "\n<!-- other metadata -->", false, body + "\n<!-- other metadata -->").ok).toBe(false);
  expect(checkCopy(title, `<div hidden>\n${body}\n</div>`).ok).toBe(false);
});
test("rejects shorthand, backticked issue URLs and unauthorized closing references", () => {
  for (const ref of ["#12", "example/project#12", "`https://github.com/example/project/issues/12`", "Fixes https://github.com/example/project/issues/12", "Closes [issue](https://github.com/example/project/issues/12)"]) expect(checkCopy(title, body + "\n" + ref).ok).toBe(false);
  expect(checkCopy(title, body + "\nCloses https://github.com/example/project/issues/12", true).ok).toBe(true);
  expect(checkCopy(title, body + "\nCloses #12", true).ok).toBe(false);
});
test("preserves code flags while rejecting prose em dashes, escaped backticks and attribution", () => {
  expect(checkCopy(title, body + "\nRun `tool --flag`\n").ok).toBe(true);
  for (const b of [body + "\nWrong\u2014copy", body + "\nRun \\`tool\\`", body + "\nGenerated by an AI assistant", body + "\nCo-Authored-By: AI assistant"]) expect(checkCopy(title, b).ok).toBe(false);
});
test("CLI reads files, emits JSON, and rejects unknown flags", () => {
  const root = mkdtempSync(join(tmpdir(), "pr-copy-"));
  try {
    const t = join(root, "title.txt"), b = join(root, "body.md"); writeFileSync(t, title); writeFileSync(b, body);
    const args = [process.execPath, resolve(import.meta.dir, "check-pr-copy.ts"), "--title-file", t, "--body-file", b];
    const good = Bun.spawnSync(args); expect(good.exitCode).toBe(0); expect(JSON.parse(good.stdout.toString()).ok).toBe(true);
    writeFileSync(b, body + "\nCloses #12"); const bad = Bun.spawnSync(args); expect(bad.exitCode).toBe(1); expect(JSON.parse(bad.stdout.toString()).ok).toBe(false);
    expect(Bun.spawnSync([...args, "--other"]).exitCode).not.toBe(0);
  } finally { rmSync(root, { recursive: true, force: true }); }
});
